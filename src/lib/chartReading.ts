export function usefulReadingKey(useful: Wuxing[]): string {
  return useful
    .slice(0, 2)
    .map((w) => WUXING_LABEL[w])
    .join("");
}

function toReading(lead: Advice, tail: Advice): ChartReadingCopy {
  return {
    marriage: [
      "姻緣的關鍵是如何選伴侶。",
      lead.partner,
      tail.partner,
      "感情順境時把溫度留給相處，別把甜蜜當成可以省略溝通的理由；逆境時先把話說短、說清楚，再決定走或留。",
      lead.prosperity.replace("順境時", "相處順的時候"),
      tail.adversity,
    ].join(""),
    career: [
      "事業先問如何選工作，再問如何選城市。",
      lead.career,
      tail.career,
      lead.city,
      tail.city,
      "職涯順境時一次只推進一兩件，把信譽做厚；逆境時能改的改、不能改的止損，再決定換崗或留任。",
      lead.prosperity,
      tail.adversity,
    ].join(""),
    health: [
      "健康落在如何選房子、如何調整作息。",
      lead.house,
      tail.house,
      lead.routine,
      tail.routine,
      "身體順境時別用應酬透支睡眠；逆境時先把熱食、作息撿回來，再談補劑與翻盤。",
      tail.prosperity,
      lead.adversity,
    ].join(""),
  };
}

const EMPTY_TAIL: Advice = {
  partner: "",
  career: "",
  city: "",
  house: "",
  routine: "",
  prosperity: "",
  adversity: "",
};

export function getChartReading(useful: Wuxing[]): ChartReadingCopy {
  const first = useful[0];
  const second = useful[1];
  if (!first) return FALLBACK;
  if (!second) return toReading(LEAD[first], EMPTY_TAIL);
  return toReading(LEAD[first], TAIL[second]);
}

export function chartReadingCharCount(copy: ChartReadingCopy): number {
  return Object.values(copy).join("").length;
}
