function beadAdvice(mm: number): string {
  if (mm <= 6) return "六毫米細巧，幾乎沒有重量，適合疊戴、細腕，或對飾品較敏感的人。";
  if (mm <= 8) return "八毫米輕巧，日常不易刮碰，適合長時間配戴與偏細的手腕。";
  if (mm <= 10) return "十毫米是沉香手串最常見的尺寸，盤玩順手，存在感適中。";
  return "十二毫米珠形飽滿、壓手，更適合作為主串，盤久了包漿也更明顯。";
}

function wristAdvice(cm: number): string {
  if (cm <= 13) return "約十三公分，貼近細腕或偏緊的配戴習慣，可依鬆緊再微調。";
  if (cm <= 15) return "約十五公分，適合偏細手腕；若平時戴錶，可與錶帶錯開一側。";
  if (cm <= 18) return "約十八公分，涵蓋大多數手腕，鬆緊以能轉過腕骨、不勒膚為度。";
  return "約二十二公分，適合偏寬手腕，或喜歡略鬆、可上下滑動把玩的人。";
}

export function describeProduct(product: Product) {
  const label = WUXING_LABEL[product.element];
  const story =
    STORIES[product.id] ??
    `${product.name}以沉香為骨，五行屬${label}。可依喜用日常配戴，盤玩時力道宜輕。`;
  const meaning = ELEMENT_MEANING[product.element];
  const shipping = product.shipping === 0 ? "免運" : formatPrice(product.shipping);

  return {
    label,
    story,
    meaning,
    shipping,
    specs: [
      ["編號", product.id],
      ["材質", "沉香木珠，彈性繩穿製"],
      ["五行", `屬${label}`],
      ["珠徑", `${product.beadMm}mm`],
      ["手圍", `${product.wristCm}cm`],
      ["運費", shipping],
    ] as [string, string][],
    wear: `${beadAdvice(product.beadMm)}${wristAdvice(product.wristCm)}新串請先在室內盤個三五天，再貼身配戴。`,
    care: "避免長時間浸泡、曝曬與香水精油；汗溼後用軟布擦乾，置於陰涼處陰乾。沉香怕燥也怕悶，可偶爾放到通風處醒香，不要密封在潮溼悶熱的袋子裡。",
  };
}
